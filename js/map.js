/* Teide marketing site — interactive archipelago map (progressive enhancement).
   The SVG is generated by website/tools/build-map.mjs from the game's heightmap;
   this file adds hover labels and the paper-plane flight between airports.
   Without JS the map is a static picture with every airport marked. */
(() => {
  'use strict';

  const outer = document.querySelector('.map-outer');
  const wrap = outer && outer.querySelector('.map-wrap');
  if (!outer || !wrap) return;
  const svg = wrap.querySelector('.map-svg');
  const tip = outer.querySelector('.map-tip');
  const plane = svg && svg.querySelector('.map-plane');
  const trail = svg && svg.querySelector('.map-trail');
  if (!svg || !tip || !plane || !trail) return;

  const reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const airports = Array.from(svg.querySelectorAll('.airport'));
  const islands = Array.from(svg.querySelectorAll('.island'));
  const byId = {};
  airports.forEach((a) => { byId[a.dataset.airport] = a; });

  // Feel knobs (map units = SVG viewBox units, ≈ 230 m each).
  const CFG = {
    start: 'TFN',          // spawn airport, as in the game
    startHeading: 252,     // TFN runway 25 take-off bearing → nose direction
    bow: 0.22,             // how far the curve bulges sideways (fraction of distance)
    bowMax: 170,
    msBase: 650,           // flight duration = msBase + distance * msPerUnit
    msPerUnit: 0.75,
    msMax: 2600,
  };

  /* ---- Scale markers/plane to screen pixels (SVG scales with width) -------- */
  const vb = svg.viewBox.baseVal;
  let k = 1;
  const pos = { x: 0, y: 0, a: CFG.startHeading };
  const placePlane = () => plane.setAttribute('transform', 'translate(' + pos.x + ' ' + pos.y + ') rotate(' + pos.a + ') scale(' + k + ')');
  const rescale = () => {
    const w = svg.getBoundingClientRect().width || vb.width;
    k = Math.max(0.8, Math.min(4, vb.width / w));
    airports.forEach((a) => a.setAttribute('transform', 'translate(' + a.dataset.x + ' ' + a.dataset.y + ') scale(' + k + ')'));
    placePlane();
  };

  /* ---- Current airport --------------------------------------------------- */
  let current = null;
  let flying = false;
  const setCurrent = (id) => {
    current = id;
    airports.forEach((a) => a.classList.toggle('is-current', a.dataset.airport === id));
  };

  /* ---- Tooltip ----------------------------------------------------------- */
  const nameEl = tip.querySelector('.map-tip-name');
  const subEl = tip.querySelector('.map-tip-sub');
  const showTip = (el) => {
    const wr = outer.getBoundingClientRect();
    let anchor, name, sub, here;
    if (el.classList.contains('airport')) {
      anchor = el.querySelector('.airport-ring') || el;
      name = el.dataset.name;
      sub = el.dataset.airport;
      here = el.dataset.airport === current;
    } else {
      anchor = el;
      name = el.dataset.name;
      sub = (el.dataset.airports || '').split(' ').filter(Boolean)
        .map((id) => byId[id] ? byId[id].dataset.name + ' · ' + id : id).join('  |  ');
      here = (el.dataset.airports || '').split(' ').includes(current);
    }
    const r = anchor.getBoundingClientRect();
    nameEl.textContent = name;
    subEl.textContent = sub;
    tip.classList.toggle('is-here', here);
    const below = r.top - wr.top < 72;            // northern islands: flip under the marker
    tip.classList.toggle('is-below', below);
    tip.style.left = (r.left + r.width / 2 - wr.left) + 'px';
    tip.style.top = ((below ? r.bottom : r.top) - wr.top) + 'px';
    tip.hidden = false;
  };
  const hideTip = () => { tip.hidden = true; };

  /* ---- Flight: cubic Bézier, nose along the tangent, trail drawn on -------- */
  const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
  const fly = (id) => {
    const target = byId[id];
    if (!target || flying || id === current) return;
    const x0 = pos.x, y0 = pos.y, x1 = +target.dataset.x, y1 = +target.dataset.y;
    const dx = x1 - x0, dy = y1 - y0, dist = Math.hypot(dx, dy) || 1;
    // Bulge away from the archipelago's mid line so long hops arc over open sea.
    const side = (y0 + y1) / 2 < vb.y + vb.height / 2 ? -1 : 1;
    const bow = Math.min(CFG.bowMax, dist * CFG.bow) * side;
    const nx = -dy / dist * bow, ny = dx / dist * bow;
    const c1x = x0 + dx * 0.3 + nx, c1y = y0 + dy * 0.3 + ny;
    const c2x = x0 + dx * 0.7 + nx, c2y = y0 + dy * 0.7 + ny;
    const at = (t) => {
      const u = 1 - t;
      return {
        x: u * u * u * x0 + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t * t * t * x1,
        y: u * u * u * y0 + 3 * u * u * t * c1y + 3 * u * t * t * c2y + t * t * t * y1,
        dx: 3 * u * u * (c1x - x0) + 6 * u * t * (c2x - c1x) + 3 * t * t * (x1 - c2x),
        dy: 3 * u * u * (c1y - y0) + 6 * u * t * (c2y - c1y) + 3 * t * t * (y1 - c2y),
      };
    };
    const finish = () => {
      pos.x = x1; pos.y = y1;
      const end = at(0.999);
      pos.a = Math.atan2(end.dy, end.dx) * 180 / Math.PI + 90;
      placePlane();
      setCurrent(id);
      flying = false;
      trail.classList.remove('is-live');          // CSS fades it out
      scrollIntoViewX(x1);
    };
    if (reduceMotion) { finish(); return; }

    flying = true;
    trail.setAttribute('d', 'M' + x0 + ' ' + y0 + ' C' + c1x + ' ' + c1y + ' ' + c2x + ' ' + c2y + ' ' + x1 + ' ' + y1);
    const total = trail.getTotalLength();
    trail.style.strokeDasharray = total + ' ' + total;
    trail.style.strokeDashoffset = total;
    trail.classList.add('is-live');
    const ms = Math.min(CFG.msMax, CFG.msBase + dist * CFG.msPerUnit);
    const t0 = performance.now();
    const step = (now) => {
      const t = Math.min(1, (now - t0) / ms);
      const e = ease(t);
      const p = at(e);
      pos.x = p.x; pos.y = p.y;
      pos.a = Math.atan2(p.dy, p.dx) * 180 / Math.PI + 90;
      placePlane();
      trail.style.strokeDashoffset = total * (1 - e);
      if (t < 1) requestAnimationFrame(step); else finish();
    };
    requestAnimationFrame(step);
  };

  // Phones pan the map sideways — keep the destination in view.
  const scrollIntoViewX = (x) => {
    if (wrap.scrollWidth <= wrap.clientWidth + 4) return;
    const px = (x - vb.x) / vb.width * svg.getBoundingClientRect().width;
    wrap.scrollTo({ left: px - wrap.clientWidth / 2, behavior: reduceMotion ? 'auto' : 'smooth' });
  };

  /* ---- Wiring ------------------------------------------------------------ */
  const targets = airports.concat(islands);
  targets.forEach((el) => {
    el.addEventListener('mouseenter', () => showTip(el));
    el.addEventListener('mouseleave', hideTip);
    el.addEventListener('focus', () => showTip(el));
    el.addEventListener('blur', hideTip);
    const go = () => {
      const id = el.classList.contains('airport') ? el.dataset.airport : (el.dataset.airports || '').split(' ')[0];
      fly(id);
      showTip(el);
    };
    el.addEventListener('click', go);
    el.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); go(); } });
  });
  // Island hover also lifts its airports' halos and vice versa.
  islands.forEach((isl) => {
    const own = (isl.dataset.airports || '').split(' ').map((id) => byId[id]).filter(Boolean);
    isl.addEventListener('mouseenter', () => own.forEach((a) => a.classList.add('is-hover')));
    isl.addEventListener('mouseleave', () => own.forEach((a) => a.classList.remove('is-hover')));
  });
  airports.forEach((a) => {
    const isl = svg.querySelector('.island[data-island="' + a.dataset.island + '"]');
    if (!isl) return;
    a.addEventListener('mouseenter', () => isl.classList.add('is-hover'));
    a.addEventListener('mouseleave', () => isl.classList.remove('is-hover'));
  });
  wrap.addEventListener('scroll', hideTip, { passive: true });

  // Boot: plane parked on the spawn runway.
  const start = byId[CFG.start] || airports[0];
  pos.x = +start.dataset.x; pos.y = +start.dataset.y;
  setCurrent(start.dataset.airport);
  rescale();
  if ('ResizeObserver' in window) new ResizeObserver(rescale).observe(svg);
  else window.addEventListener('resize', rescale);
})();
